#!/usr/bin/env python3
"""Builds the per-page translation bundles the pages load.

Reads the English source table, the manifest of which page needs which keys,
and whatever translations exist in assets/i18n-lang/<lang>.json, then writes
one bundle per page containing only that page's strings.

A key with no translation yet simply ships English for that language, which
is what the switcher already falls back to - so a half-finished language
degrades to today's behaviour instead of blanking the page.

    python3 tools/i18n_build.py
"""
import json, os

ROOT  = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANGS = ('fr', 'it', 'es')

def main():
    src = json.load(open(os.path.join(ROOT, 'assets', 'i18n-source.json'), encoding='utf-8'))
    man = json.load(open(os.path.join(ROOT, 'assets', 'i18n-manifest.json'), encoding='utf-8'))
    tr  = {}
    for L in LANGS:
        p = os.path.join(ROOT, 'assets', 'i18n-lang', '%s.json' % L)
        tr[L] = json.load(open(p, encoding='utf-8')) if os.path.exists(p) else {}

    done = {L: 0 for L in LANGS}
    total = 0
    for slug, keys in sorted(man.items()):
        rows = {}
        for k in keys:
            en = src.get(k)
            if en is None:
                continue
            row = {'en': en}
            for L in LANGS:
                v = tr[L].get(k)
                if v:
                    row[L] = v
            rows[k] = row
        out = os.path.join(ROOT, 'assets', 'i18n', slug + '.js')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, 'w', encoding='utf-8') as fh:
            fh.write('/* Generated by tools/i18n_build.py - do not edit by hand. */\n')
            fh.write('window.JV_STRINGS = Object.assign(window.JV_STRINGS || {}, ')
            json.dump(rows, fh, ensure_ascii=False, separators=(',', ':'), sort_keys=True)
            fh.write(');\n')

    for k in src:
        total += 1
        for L in LANGS:
            if tr[L].get(k):
                done[L] += 1
    print('bundles written: %d' % len(man))
    print('strings: %d' % total)
    for L in LANGS:
        print('  %s %5d / %d  (%.1f%%)' % (L, done[L], total, 100.0*done[L]/total))

if __name__ == '__main__':
    main()
